"""Run: python -m src.export_frontend_data -> frontend/src/mockData.js
Embeds the REAL metrics/waste/test predictions so the UI still demos properly when the backend is offline."""
import csv, json
import pandas as pd
from src.features import MENU_BY_MEAL, MENU

raw = pd.read_csv("data/mess_synthetic_data.csv")
means = raw.groupby("menu_item").plates_served.mean().round(1).to_dict()
meal_means = raw.groupby("meal").plates_served.mean().round(1).to_dict()
data = {
    "options": {"meals": ["Breakfast", "Lunch", "Dinner"], "menu_by_meal": MENU_BY_MEAL, "special": [k for k, v in MENU.items() if v],
                "fixed_plates": {"Breakfast": 650, "Lunch": 850, "Dinner": 900}, "buffer": 1.05, "kg_per_plate": 0.35,
                "history_end": "2025-12-31", "model": json.load(open("models/model_meta.json"))["model"], "data_is": "simulated"},
    "metrics": json.load(open("reports/metrics.json")),
    "metricsDetailed": json.load(open("reports/metrics_detailed.json")),
    "waste": json.load(open("reports/waste.json")),
    "testPredictions": list(csv.DictReader(open("reports/test_predictions.csv"))),
    "menuMeans": means, "mealMeans": meal_means,
}
js = "// AUTO-GENERATED by src/export_frontend_data.py - real project results, used as offline fallback.\n"
js += "export const MOCK = " + json.dumps(data, indent=1) + "\n"
js += r"""
const FIXED = MOCK.options.fixed_plates

function hash(str) { let h = 0; for (const c of str) h = (h * 31 + c.charCodeAt(0)) | 0; return Math.abs(h) }

// Rough stand-in for the real model (offline demo only): menu average x weekday x condition multipliers.
export function mockPredict(b) {
  const d = new Date(b.date + 'T00:00:00')
  const dow = (d.getDay() + 6) % 7
  const base = MOCK.menuMeans[b.menu_item] ?? MOCK.mealMeans[b.meal]
  let p = base * (dow >= 5 ? 0.93 : 1.0)
  if (b.is_holiday) p *= 0.85
  if (b.is_exam_period) p *= 1.08
  if (b.is_vacation) p *= 0.55
  if (b.is_event) p *= 1.08
  p += Math.min(b.rain_mm ?? 0, 25) * 1.5   // in the data, rain slightly RAISES mess demand
  p += ((hash(b.date + b.meal) % 21) - 10)
  return pack(Math.max(p, 0), b.meal)
}

export function pack(pred, meal) {
  const cook = Math.round(pred * MOCK.options.buffer)
  const leftFixed = Math.max(FIXED[meal] - pred, 0)
  const leftFc = Math.max(cook - pred, 0)
  return { predicted_plates: Math.round(pred), suggested_cook_plates: cook,
           expected_saving_kg: Math.round(Math.max((leftFixed - leftFc) * MOCK.options.kg_per_plate, 0) * 10) / 10,
           lag_source: 'offline-demo' }
}

export function mockWeek(b) {
  const out = []
  for (let i = 0; i < 7; i++) {
    const d = new Date(b.start_date + 'T00:00:00'); d.setDate(d.getDate() + i)
    const iso = d.toISOString().slice(0, 10)
    const menu = (b.menu_items && b.menu_items[i]) || b.menu_item
    out.push({ date: iso, weekday: d.toLocaleDateString('en-US', { weekday: 'short' }), menu_item: menu,
               ...mockPredict({ ...b, date: iso, menu_item: menu }) })
  }
  return out
}
"""
open("frontend/src/mockData.js", "w").write(js)
print("wrote frontend/src/mockData.js", len(js) // 1024, "KB")
